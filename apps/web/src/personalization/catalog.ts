export function presentationTokens(preferences: PresentationPreferences) {
  const theme = THEMES.find((candidate) => candidate.id === preferences.themeId) ?? THEMES[0]
  const appearance = preferences.scheme === 'theme' ? theme.defaultAppearance : preferences.scheme
  const surface = theme.appearances[appearance]
  const palette = (PALETTES.find((candidate) => candidate.id === preferences.paletteId) ??
    PALETTES[0])[appearance]
  return {
    appearance,
    canvas: surface.canvas,
    surface: surface.surface,
    ink: surface.text,
    muted: surface.muted,
    border: surface.borderDecorative,
    controlBorder: surface.borderControl,
    nav: surface.navSurface,
    navInk: surface.navText,
    accent: palette.primary,
    accentText: palette.primary,
    accentInk: palette.onPrimary,
    accentSoft: palette.soft,
    accentHover: palette.hover,
    focus: appearance === 'dark' ? '#FFFFFF' : '#111827',
    radius: theme.tokens.radiusPanel,
    controlRadius: theme.tokens.radiusControl,
    semantic: SEMANTIC_TOKENS,
  }
}
